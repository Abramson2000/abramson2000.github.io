// ============ extra-gate: курсы-выжимки x2 (переписка) и x3 (телефон) убраны из «Дополнительно» ============
// Решение Саши (09.09.2026): «два курса по книгам убирай вообще. В Допах останется только один» (x4).
// Курсы исключаются из показа для ВСЕХ, включая владельца. Контент в исходниках не тронут —
// при необходимости файл можно отключить, и курсы вернутся.
// Подключается ПОСЛЕ data.js и bariga-data.js, ДО app.js.
(function () {
  // SPIN_DATA — top-level const (глобальная лексическая переменная, НЕ на window)
  if (typeof SPIN_DATA === 'undefined' || !SPIN_DATA.extra) return;
  SPIN_DATA.extra = SPIN_DATA.extra.filter(function (x) {
    return !(x && (x.id === 'x2' || x.id === 'x3'));
  });
})();
